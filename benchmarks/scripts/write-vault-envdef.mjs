#!/usr/bin/env node
// Two responsibilities, sharing name-resolution logic so a "load secrets" CI
// step stays a one-liner pair:
//
//   1. Emit a Namespace vault --envdef file mapping KEY -> <vault object_id>.
//      Looked up at runtime via `nsc vault list --output json` so the
//      downstream `nsc vault export` can resolve each entry against the actual
//      vault (placeholders would make the export step fail).
//
//   2. --emit-masks: print `::add-mask::VALUE` for each name currently in
//      this process's env. Pair this with (1) in the same GH Actions step so
//      any accidental downstream echo of a loaded var is redacted in CI logs.
//      (The previous scripts/load-ns-secrets.mjs did the same thing via
//      ::add-mask::; nsc does not.)
//
// Name-resolution mirrors benchmarks/scripts/provider-vars.json (generated by
// gen-provider-vars.ts) so per-job secret scoping stays the same — only the
// loader changes.
//
// Usage:
//   write-vault-envdef.mjs --mode browser --provider hyperbrowser
//   write-vault-envdef.mjs --mode ai-gateway                    # mode union
//   write-vault-envdef.mjs NAME [NAME ...]                      # explicit names
//   write-vault-envdef.mjs --mode browser --provider hyperbrowser --emit-masks
//   write-vault-envdef.mjs --placeholder ...                   # emit KEY=sec_dummy (dev/test)
//
// Consumed by:
//   eval "$(nsc vault export --envdef /tmp/vault.envdef --shell=bash)"
import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const PLACEHOLDER = 'sec_dummy';

const argv = process.argv.slice(2);
const valueIdxs = new Set();
function flagValue(name) {
  const i = argv.indexOf(name);
  if (i === -1) return null;
  valueIdxs.add(i + 1);
  return argv[i + 1] ?? null;
}
const mode = flagValue('--mode');
const provider = flagValue('--provider');
const placeholder = argv.includes('--placeholder');
const emitMasks = argv.includes('--emit-masks');
const maskFrom = flagValue('--mask-from');
const positional = argv.filter((a, i) => !a.startsWith('--') && !valueIdxs.has(i));

// 1. --emit-masks / --mask-from: print ::add-mask::VALUE for each name
//    currently set in env. Pair with the envdef write in the same step so
//    this job's logs are safe from accidental env echoes in later steps.
//    --mask-from <path> reads names from an already-written envdef file
//    (uniform across all 7 workflows without re-passing the same selector).
if (emitMasks || maskFrom) {
  let maskNames;
  if (maskFrom) {
    maskNames = readFileSync(maskFrom, 'utf8')
      .split('\n')
      .map((l) => l.trim().split('=')[0])
      .filter(Boolean);
  } else {
    // --emit-masks without --mask-from: re-run name resolution so callers
    // can re-issue the same selector (e.g. for an in-step replay that doesn't
    // touch the envdef file).
    // We avoid calling resolveNames() here because resolveNames() exits 2 when
    // no selector is given; the contract for --emit-masks alone is that the
    // caller passes a selector (otherwise use --mask-from with /dev/null).
    maskNames = inlineResolveNames();
    if (!maskNames || maskNames.length === 0) {
      console.error('Usage: --emit-masks requires the same selector (--mode/--provider/NAMES) as the envdef, or use --mask-from <path>');
      process.exit(2);
    }
  }
  let count = 0;
  for (const n of maskNames) {
    const val = process.env[n];
    if (val) {
      // Multi-line secrets: mask every line independently so the whole line
      // shows masked in logs even if it's split. (load-ns-secrets.mjs did the
      // same; ::add-mask:: only matches exact substrings.)
      for (const line of String(val).split(/\r?\n/)) {
        if (line.length) {
          console.log(`::add-mask::${line}`);
          count++;
        }
      }
    }
  }
  if (count === 0) {
    console.error(`--emit-masks: none of the requested names are set in env`);
  }
  process.exit(0);
}

// 2. Resolve which KEYs we want for the envdef write path. Errors if the
//    caller passed neither a selector nor a --mask-from shortcut above.
function inlineResolveNames() {
  if (mode && provider) {
    const manifest = JSON.parse(readFileSync(new URL('./provider-vars.json', import.meta.url), 'utf8'));
    const names = manifest[mode]?.[provider];
    if (!names) {
      console.error(`No manifest entries for ${mode}/${provider}. Known modes: ${Object.keys(manifest).join(', ')}`);
      process.exit(1);
    }
    return names;
  }
  if (mode) {
    const manifest = JSON.parse(readFileSync(new URL('./provider-vars.json', import.meta.url), 'utf8'));
    const modeMap = manifest[mode];
    if (!modeMap) {
      console.error(`Unknown --mode "${mode}". Known modes: ${Object.keys(manifest).join(', ')}`);
      process.exit(1);
    }
    const seen = new Set();
    for (const vars of Object.values(modeMap)) for (const v of vars) seen.add(v);
    return [...seen].sort();
  }
  if (positional.length) return positional;
  return [];
}

const names = inlineResolveNames();
if (names.length === 0) {
  console.error('Usage:');
  console.error('  write-vault-envdef.mjs --mode <mode> --provider <provider>');
  console.error('  write-vault-envdef.mjs --mode <mode>             # union of every provider in mode');
  console.error('  write-vault-envdef.mjs NAME [NAME ...]            # explicit names');
  console.error('Flags:');
  console.error('  --placeholder        emit KEY=sec_dummy (skip vault lookup; dev/test only)');
  console.error('  --emit-masks         print ::add-mask::VALUE for each name in env (CI redaction)');
  console.error('  --mask-from <path>   read names from an existing envdef file and emit ::add-mask:: (CI redaction)');
  process.exit(2);
}

// 3. Emit placeholders if asked, otherwise look up real object IDs from the vault.
if (placeholder) {
  process.stdout.write(names.map((n) => `${n}=${PLACEHOLDER}\n`).join(''));
  process.exit(0);
}

let vault;
try {
  vault = JSON.parse(execSync('nsc vault list --output json', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }));
} catch (e) {
  console.error(`nsc vault list failed: ${e.stderr?.toString().trim() || e.message || e}`);
  process.exit(2);
}

// Build the env-var name -> object_id map. Mirrors the lookup load-ns-secrets.mjs
// used against the Connect JSON API: prefer the `name=` label (or any array-
// element whose `name`-ish key matches), fall through to a description that
// matches the env-var name pattern. Production vault entries sometimes store
// the env-var name on top-level `name`, in `labels` as an array, in `labels`
// as an object, or in `description` only — so we try them in that order.
const ENV_NAME = /^[A-Z][A-Z0-9_]*$/;

// Forms supported for "labels":
//   1. array of { name: "name", value: "OPENROUTER_API_KEY" } objects  (devbox)
//   2. object/record mapping label-key -> value                        (older devbox)
//   3. array of "name=value" strings                                  (rare fallback)
// We return a list of [labelKey, labelValue] pairs so the rest of the code
// doesn't care about the wire format.
function readLabels(obj) {
  if (Array.isArray(obj.labels)) {
    return obj.labels
      .map((l) => {
        if (l == null) return null;
        if (typeof l === 'string') {
          const i = l.indexOf('=');
          return i === -1 ? null : [l.slice(0, i).trim(), l.slice(i + 1).trim()];
        }
        if (typeof l === 'object') {
          const k = l.name ?? l.key ?? l.label ?? null;
          const v = l.value ?? l.val ?? null;
          return k && v ? [String(k), String(v)] : null;
        }
        return null;
      })
      .filter(Boolean);
  }
  if (obj.labels && typeof obj.labels === 'object') {
    return Object.entries(obj.labels)
      .filter(([, v]) => v != null)
      .map(([k, v]) => [k, String(v)]);
  }
  return [];
}

function labelOf(obj, key) {
  for (const [k, v] of readLabels(obj)) {
    if (k === key) return v;
  }
  return undefined;
}

const idByName = {};
const anonCount = { byLabel: 0, byDesc: 0, byTopName: 0, neither: 0 };
for (const obj of vault) {
  const id = obj.object_id;
  if (!id) continue;
  const nameLabel = labelOf(obj, 'name') ?? labelOf(obj, 'env_var') ?? labelOf(obj, 'key');
  const desc = (obj.description || '').trim();
  const topName = (obj.name || obj.title || obj.secret_name || '').trim();
  const name = nameLabel || (ENV_NAME.test(desc) ? desc : undefined) || (ENV_NAME.test(topName) ? topName : undefined);
  const via = nameLabel ? 'label' : (ENV_NAME.test(desc) ? 'description' : (ENV_NAME.test(topName) ? 'topname' : 'none'));
  if (!name) { anonCount.neither++; continue; }
  if (!idByName[name]) {
    idByName[name] = id;
    if (via === 'label') anonCount.byLabel++;
    else if (via === 'description') anonCount.byDesc++;
    else if (via === 'topname') anonCount.byTopName++;
  }
}

const out = [];
const missing = [];
for (const n of names) {
  const id = idByName[n];
  if (id) out.push(`${n}=${id}`);
  else missing.push(n);
}

if (missing.length) {
  // Mirror load-ns-secrets.mjs: warning, not failure. The bench itself will
  // surface a truly-missing cred explicitly. Always emit a small summary of
  // how vault entries were indexed so production drift (e.g. labels removed,
  // schema changed) shows up in CI logs without crashing this step.
  console.error(`WARNING: vault missing keys for names: ${missing.join(', ')}`);
  console.error(`  indexed=${vault.length} via-label=${anonCount.byLabel} via-description=${anonCount.byDesc} via-topname=${anonCount.byTopName} unindexed=${anonCount.neither}`);
  // Dump the schema of one entry so we can see whether production's nsc vault
  // list returns labels/description in a different shape than this script
  // expects. Long entries are truncated to keep CI logs readable.
  if (vault[0]) {
    const sample = vault[0];
    const labelPairs = readLabels(sample).slice(0, 4).map(([k, v]) => `${k}=${JSON.stringify(v.slice(0, 32))}`).join(' ');
    console.error(`  sample-keys=${Object.keys(sample).join(',')} labels=${Array.isArray(sample.labels) ? `array(${sample.labels.length})` : (sample.labels && typeof sample.labels === 'object' ? 'map' : 'none')} sample-labels=${labelPairs || '(none)'} sample-description=${JSON.stringify((sample.description || '').slice(0, 64))}`);
  }
}

process.stdout.write(out.join('\n') + (out.length ? '\n' : ''));
